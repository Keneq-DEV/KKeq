export function t(key: keyof typeof TEXT, values: Record<string, string> = {}): string {
  const language = getLanguage();
  let message: string = TEXT[key][language];
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, value);
  }
  return message;
}
